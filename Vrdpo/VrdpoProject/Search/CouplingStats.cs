namespace VrdpoProject
{
    // Per-iteration feasibility counts of the inter-route candidates of the relocation and swap scans, by
    // the type of the delivery location(s) the candidate transfers between routes (settings.countCoupling).
    //
    // A stop is an IDL (individual delivery location: private address, Location.Type 2) or an SDL (shared
    // delivery location: locker / pickup point, Location.Type 1). Categories:
    //
    //   relocate   the moved stop is an IDL or an SDL                          idl, sdl
    //   swap       the two exchanged stops are both IDLs, one of each, or both SDLs   idl_idl, idl_sdl, sdl_sdl
    //
    // For every inter-route candidate (origin and target route differ; relocations into an empty route are
    // not counted, they open a vehicle rather than transfer between two routes):
    //
    //   evaluated    the candidate was generated by the scan, whatever its cost
    //   capacityOk   the receiving route(s) stay within the vehicle capacity
    //   feasible     capacityOk and the receiving route(s) stay time-window feasible
    //
    // Feasibility is checked for every candidate whatever its cost: the scans' cost-first pruning does not
    // apply to the counters (the scans themselves only check the candidates cheaper than the best found so
    // far). Nothing else changes, the move that is applied is the same as without counting. Inter-route
    // relocations and swaps change neither the served options nor the locations, so shared-location
    // capacities and service levels are untouched: capacity and time windows are the only constraints.
    public sealed class CouplingStats
    {
        public const int Relocate = 0, Swap = 1;
        public static readonly string[] Operators = { "relocate", "swap" };
        public static readonly string[][] Categories =
        {
            new[] { "idl", "sdl" },
            new[] { "idl_idl", "idl_sdl", "sdl_sdl" },
        };

        public readonly long[][] Evaluated = NewCounters();
        public readonly long[][] CapacityOk = NewCounters();
        public readonly long[][] Feasible = NewCounters();

        private static long[][] NewCounters()
        {
            var counters = new long[Operators.Length][];
            for (int op = 0; op < Operators.Length; op++)
            {
                counters[op] = new long[Categories[op].Length];
            }
            return counters;
        }

        public static bool IsShared(Location location) => location.Type == 1;

        // Category of a relocation by the moved stop's location.
        public static int RelocationCategory(Location moved) => IsShared(moved) ? 1 : 0;

        // Category of a swap by the two exchanged stops' locations: the number of shared ones.
        public static int SwapCategory(Location first, Location second) => (IsShared(first) ? 1 : 0) + (IsShared(second) ? 1 : 0);

        public void Reset()
        {
            for (int op = 0; op < Operators.Length; op++)
            {
                Array.Clear(Evaluated[op]);
                Array.Clear(CapacityOk[op]);
                Array.Clear(Feasible[op]);
            }
        }

        // `count` candidates of the category rejected by the vehicle capacity.
        public void RecordCapacityInfeasible(int op, int category, long count)
        {
            Evaluated[op][category] += count;
        }

        // One candidate of the category that passed the capacity check, time-window feasible or not.
        public void Record(int op, int category, bool feasible)
        {
            Evaluated[op][category]++;
            CapacityOk[op][category]++;
            if (feasible)
            {
                Feasible[op][category]++;
            }
        }

        // Adds the counts of another iteration (per-solve totals).
        public void Add(CouplingStats other)
        {
            for (int op = 0; op < Operators.Length; op++)
            {
                for (int c = 0; c < Categories[op].Length; c++)
                {
                    Evaluated[op][c] += other.Evaluated[op][c];
                    CapacityOk[op][c] += other.CapacityOk[op][c];
                    Feasible[op][c] += other.Feasible[op][c];
                }
            }
        }
    }
}
